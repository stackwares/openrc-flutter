export type Language = (typeof LANGUAGES)[number];

/** The supported language for a `lang` parameter, or English. */
export function parseLanguage(param: string | null): Language {
  const known = LANGUAGES.find((l) => l.toLowerCase() === param?.toLowerCase());
  return known ?? "en";
}

